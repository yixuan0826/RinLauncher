"""启动方式：注册表 Run 值（登录时启动）与任务计划（管理员自启动）的统一管理。

「管理员自启动」要在任务计划程序里建一条最高权限的登录触发任务，创建 / 删除
都需要提权 —— 界面线程不直接干这事，而是把活交给本程序的无界面辅助分支：

    RinLauncher.exe --set-startup-mode=admin|normal|off

由 ``spawn_apply_elevated`` 用 runas 拉起来（会弹一次 UAC）。界面在稍后通过
``rin_launcher.autostart.startup_state`` 回查系统里的真实状态。

只判断「任务存不存在」是不够的：更新 / 移动目录后，任务可能还指着旧的
python.exe 或旧 exe。登录时任务计划只会报 0x80070002，界面却仍显示「管理员
自启动」。这里同时校验任务动作和注册表值是否指向**当前**程序。
"""

from __future__ import annotations

import logging
import os
import subprocess
import sys
import threading
import time
import xml.etree.ElementTree as ET
from pathlib import Path

from rin_launcher import atomic, runtime
from rin_launcher.startup_command import commands_match

logger = logging.getLogger(__name__)

#: 任务计划里那条目的名称（任务计划程序里看到的就是它）。
TASK_NAME = "Rin Launcher"
#: 别再闪黑窗：schtasks 的调用全部隐藏控制台。
_NO_WINDOW = getattr(subprocess, "CREATE_NO_WINDOW", 0)

# 任务状态的读缓存：schtasks 一次要 70~200ms，界面路径（设置页打开 / 轮询）
# 绝不能同步等它 —— 启动时在后台预热，之后读取走缓存、刷新走异步线程。
# 缓存项是 (取值时间, 是否存在, 是否指向当前程序)。
_TASK_CACHE_TTL = 30.0
_task_cache: tuple[float, bool, bool] | None = None
_task_lock = threading.Lock()


def _schtasks(args: list[str]) -> subprocess.CompletedProcess[bytes]:
    return subprocess.run(
        ["schtasks", *args],
        capture_output=True, check=False, creationflags=_NO_WINDOW)


def _decode_output(data: bytes) -> str:
    """schtasks /XML 在中文系统上返回 UTF-16LE；/Query 普通输出是 OEM 代码页。"""
    if not data:
        return ""
    if data.startswith(b"\xff\xfe") or data.startswith(b"\xfe\xff"):
        return data.decode("utf-16", errors="replace")
    for encoding in ("utf-8-sig", "mbcs", "latin-1"):
        try:
            return data.decode(encoding)
        except (LookupError, UnicodeDecodeError):
            continue
    return data.decode("utf-8", errors="replace")


def _query_task_xml() -> str:
    result = _schtasks(["/Query", "/TN", TASK_NAME, "/XML"])
    if result.returncode != 0:
        return ""
    return _decode_output(result.stdout)


def parse_task_command(xml_text: str) -> str:
    """从任务计划 XML 里取出第一条 Exec 的 Command + Arguments。"""
    text = str(xml_text or "").strip()
    if not text:
        return ""
    try:
        root = ET.fromstring(text)
    except ET.ParseError:
        logger.debug("无法解析任务计划 XML", exc_info=True)
        return ""
    for node in root.iter():
        if node.tag.rsplit("}", 1)[-1] != "Exec":
            continue
        command = ""
        arguments = ""
        for child in node:
            name = child.tag.rsplit("}", 1)[-1]
            if name == "Command":
                command = (child.text or "").strip()
            elif name == "Arguments":
                arguments = (child.text or "").strip()
        if command:
            return f"{command} {arguments}".strip()
    return ""


def _source_launcher_path() -> Path:
    """源码模式的自启动入口脚本：绕过「Run 值没有工作目录」的限制。"""
    override = os.environ.get("RINLAUNCHER_CONFIG_DIR", "").strip()
    if override:
        base = Path(override).expanduser()
    else:
        appdata = os.environ.get("APPDATA")
        base = Path(appdata) if appdata else Path.home() / "AppData" / "Roaming"
        base = base / "RinLauncher"
    return base / "startup-launcher.py"


def _source_launcher_text() -> str:
    root = str(runtime.bundle_root())
    return (
        "# Generated by Rin Launcher for source-mode autostart.\n"
        "import runpy, sys\n"
        f"sys.path.insert(0, {root!r})\n"
        "runpy.run_module('rin_launcher.main', run_name='__main__')\n"
    )


def _write_source_launcher() -> bool:
    """写一个很小的 python 启动器：``pythonw startup-launcher.py`` 即可。"""
    path = _source_launcher_path()
    text = _source_launcher_text()
    try:
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            return True
    except OSError:
        pass
    return atomic.atomic_write_text(path, text)


def startup_launcher_command(write: bool = True) -> str:
    """写进注册表 / 任务计划的启动命令。

    冻结包直接用 exe。源码模式不能写 ``python main.py``：按路径启动会走错
    bootstrap（相对导入与资源根都不对）。这里生成一个 ``-m`` 启动器，放在
    用户配置目录里，Run 值不需要工作目录也能起来。
    """
    if runtime.is_frozen():
        return f'"{sys.executable}"'
    pythonw = Path(sys.executable).with_name("pythonw.exe")
    runner = pythonw if pythonw.exists() else Path(sys.executable)
    launcher = _source_launcher_path()
    if write and not _write_source_launcher():
        logger.warning("无法写入源码模式自启动入口：%s", launcher)
    return f'"{runner}" "{launcher}"'


def _app_command() -> str:
    """兼容旧调用点：返回当前程序的自启动命令。"""
    return startup_launcher_command()


def _query_task_status() -> tuple[bool, bool]:
    """返回 (任务是否存在, 任务是否指向当前程序)。"""
    if sys.platform != "win32":
        return False, False
    xml_text = _query_task_xml()
    if not xml_text:
        return False, False
    command = parse_task_command(xml_text)
    current = (bool(command)
               and commands_match(command, startup_launcher_command(write=False))
               and _launcher_is_current())
    return True, current


def _launcher_is_current() -> bool:
    """源码模式的启动器内容是否还指向当前仓库。

    任务 / 注册表里存的只是「pythonw + startup-launcher.py」，路径本身不会随
    仓库移动而变化；启动器脚本里内嵌的 bundle_root 才是真正的入口。仓库搬家
    后只比较命令会误判成「仍然有效」，这里把内容也查一遍。
    """
    if runtime.is_frozen():
        return True
    path = _source_launcher_path()
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return False
    return text == _source_launcher_text()


def _query_task_exists() -> bool:
    """兼容测试 / 旧调用：只问任务在不在。"""
    return _query_task_status()[0]


def _store_task_cache(exists: bool, current: bool | None = None) -> None:
    global _task_cache
    with _task_lock:
        _task_cache = (time.monotonic(), exists, exists if current is None else current)


def _cached_task_status(force: bool = False) -> tuple[bool, bool] | None:
    with _task_lock:
        cached = _task_cache
    if cached is None:
        return None
    if not force and (time.monotonic() - cached[0]) >= _TASK_CACHE_TTL:
        return None
    return cached[1], cached[2]


def task_exists(force: bool = False) -> bool:
    """任务计划里有没有我们那条「管理员自启动」任务。

    走 30 秒缓存（避免界面路径反复起 schtasks 子进程）；切换启动方式这种要
    下判断的地方传 ``force=True`` 拿新鲜值。
    """
    if not force:
        cached = _cached_task_status()
        if cached is not None:
            return cached[0]
    exists, current = _query_task_status()
    _store_task_cache(exists, current)
    return exists


def task_is_current(force: bool = False) -> bool:
    """任务是否存在且动作指向当前程序。

    不传 ``force`` 时只读缓存；缓存还没预热时返回 False，绝不在界面线程上
    同步起 schtasks。设置页的异步刷新 / 启动预热会把它填上。
    """
    if not force:
        cached = _cached_task_status()
        return cached[1] if cached is not None else False
    exists, current = _query_task_status()
    _store_task_cache(exists, current)
    return current


def task_exists_cached() -> bool:
    """只读缓存（还没探测过时先当 False）；绝不阻塞界面线程。"""
    cached = _cached_task_status()
    return cached[0] if cached is not None else False


def refresh_task_exists_async(on_done=None) -> None:
    """后台线程刷一遍任务状态；完成后调 ``on_done(值)``（回调里发 Qt 信号回主线程）。"""
    def work() -> None:
        from rin_launcher import ecoqos

        ecoqos.enable_current_thread()
        exists, current = _query_task_status()
        _store_task_cache(exists, current)
        if on_done is not None:
            try:
                on_done(exists)
            except Exception:
                logger.exception("task-state refresh callback failed")

    threading.Thread(target=work, name="task-state-refresh", daemon=True).start()


def create_task() -> bool:
    """创建 / 覆盖「管理员自启动」任务（登录触发 + 最高权限）。需要管理员。"""
    command = startup_launcher_command()
    if runtime.is_frozen():
        if not Path(sys.executable).is_file():
            logger.error("当前 exe 不存在，无法创建自启动任务：%s", sys.executable)
            return False
    elif not _source_launcher_path().is_file():
        logger.error("源码模式的自启动入口没有落盘，无法创建任务")
        return False
    result = _schtasks([
        "/Create", "/F", "/TN", TASK_NAME, "/TR", command,
        "/SC", "ONLOGON", "/RL", "HIGHEST",
    ])
    if result.returncode != 0:
        logger.error("创建任务计划失败: %s",
                     _decode_output(result.stderr or result.stdout).strip())
        return False
    _store_task_cache(True, True)
    return True


def delete_task() -> bool:
    """删掉任务；本来就不存在算成功。需要管理员（任务以最高权限注册）。"""
    if not task_exists(force=True):
        _store_task_cache(False, False)
        return True
    result = _schtasks(["/Delete", "/F", "/TN", TASK_NAME])
    if result.returncode != 0:
        logger.error("删除任务计划失败: %s",
                     _decode_output(result.stderr or result.stdout).strip())
        return False
    _store_task_cache(False, False)
    return True


def startup_state() -> str:
    """系统里的真实启动方式：admin（任务在当前程序上）/ normal / off。

    只读缓存、不起子进程 —— 界面路径永不阻塞；缓存由启动预热和
    ``refresh_task_exists_async`` 更新。
    """
    if sys.platform != "win32":
        return "off"
    from rin_launcher.elevation import run_on_startup_current

    if task_is_current():
        return "admin"
    command = startup_launcher_command(write=False)
    if _launcher_is_current() and run_on_startup_current(command):
        return "normal"
    return "off"


def apply_startup_mode(mode: str) -> bool:
    """把系统的启动项调成 ``mode``；注册表与任务计划二选一，永远互斥。

    这个函数会在提权后的辅助进程里被调用（注册 / 删除最高权限任务需要管理员）。
    """
    from rin_launcher.elevation import set_run_on_startup

    command = startup_launcher_command()
    if mode == "admin":
        # 开管理员自启动时顺手撤掉注册表项，避免登录时启两遍。
        set_run_on_startup(False, command)
        return create_task()
    if mode == "normal":
        if not delete_task():
            return False
        return set_run_on_startup(True, command)
    # off：两边都收拾干净。
    if not delete_task():
        return False
    return set_run_on_startup(False, command)


def spawn_apply_elevated(mode: str) -> bool:
    """以管理员身份拉起本程序的无界面辅助分支去调启动项（会弹一次 UAC）。"""
    from rin_launcher.elevation import run_elevated

    if runtime.is_frozen():
        return run_elevated(sys.executable, f"--set-startup-mode={mode}")
    return run_elevated(
        sys.executable,
        f'"{Path(sys.argv[0]).resolve()}" --set-startup-mode={mode}')
